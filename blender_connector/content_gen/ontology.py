"""Render the Blender ontology file (CONN-BLENDER-CONNECTOR-CONTENT-R003).

A pure function from the source and its tool snapshot to Turtle text.
The single pack file holds the ``owl:Ontology`` node, the pack classes
(``:BlenderApp``, ``:BlenderTool``, ``:BlenderUseCase``) and the
linking properties under the app namespace, the app individual, the
domain classes and one ``:BlenderUseCase`` individual per
functionality. A domain class naming a shared core parent carries that
edge under both the shared ``kg#`` namespace and the organization base,
because the serving engine fleet runs two medulla generations whose
parent catalogs sit under different bases.
"""

from __future__ import annotations

import re

from blender_connector.content_gen.errors import (
    CONTENT_PARENT_UNKNOWN,
    CONTENT_PROMPT_TOOL_UNKNOWN,
    ContentError,
)
from blender_connector.content_gen.sources import (
    ALLOWED_PARENTS,
    BlenderSource,
    ToolSnapshot,
    skill_name,
)

_KG = "http://knuckles.team/kg"
_KG_NS = f"{_KG}#"
#: The organization-base core namespace.
_BASE_CORE_NS = "https://knuckles-team.github.io/ontology/core#"
#: The shared parents that carry the dual-namespace edges.
_CORE_PARENTS = frozenset(ALLOWED_PARENTS)

GENERATOR_NOTE = "Generated by scripts/generate_blender_content.py; do not edit."


def _iri(app: str) -> str:
    return f"{_KG}/{app}"


def _tool_ref(app: str, tool: str) -> str:
    """The namespaced tool name content carries for one upstream tool."""
    return f"{app}_{tool}"


def _check_tools(app: str, tools, snapshot: ToolSnapshot) -> None:
    known = snapshot.names()
    for tool in tools:
        if tool not in known:
            raise ContentError(
                CONTENT_PROMPT_TOOL_UNKNOWN,
                f"{app}: tool {tool!r} is not in the snapshot",
            )


def render_ontology(source: BlenderSource, snapshot: ToolSnapshot) -> str:
    """The Turtle text of ``ontology/blender.ttl``."""
    app = source.app
    lines = [
        f"@prefix : <{_KG_NS}> .",
        f"@prefix core: <{_BASE_CORE_NS}> .",
        f"@prefix app: <{_iri(app)}#> .",
        "@prefix owl: <http://www.w3.org/2002/07/owl#> .",
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
        "@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .",
        "",
        f"<{_iri(app)}> a owl:Ontology ;",
        f'    rdfs:label "{app}" ;',
        f'    rdfs:comment "{GENERATOR_NOTE}" .',
        "",
        "app:BlenderApp a owl:Class ;",
        '    rdfs:label "Blender App" ;',
        '    rdfs:comment "One Blender application surface served as an upstream MCP server." ;',
        "    rdfs:subClassOf :Application, core:Application .",
        "",
        "app:BlenderTool a owl:Class ;",
        '    rdfs:label "Blender Tool" ;',
        '    rdfs:comment "One tool exposed by the Blender upstream on its MCP surface." ;',
        "    rdfs:subClassOf :Tool, core:Tool .",
        "",
        "app:BlenderUseCase a owl:Class ;",
        '    rdfs:label "Blender Use Case" ;',
        '    rdfs:comment "An authored Blender task, walking an ordered set of upstream tools." ;',
        "    rdfs:subClassOf :Task, core:Task .",
        "",
        "app:appNamespace a owl:DatatypeProperty ;",
        '    rdfs:label "app namespace" ;',
        '    rdfs:comment "The MCP namespace of the app." ;',
        "    rdfs:domain app:BlenderApp ;",
        "    rdfs:range xsd:string .",
        "",
        "app:forApp a owl:ObjectProperty ;",
        '    rdfs:label "for app" ;',
        '    rdfs:comment "Links a use case to the app it is performed in." ;',
        "    rdfs:domain app:BlenderUseCase ;",
        "    rdfs:range app:BlenderApp .",
        "",
        "app:usesToolName a owl:DatatypeProperty ;",
        '    rdfs:label "uses tool name" ;',
        '    rdfs:comment "A namespaced tool name the use case walks through." ;',
        "    rdfs:domain app:BlenderUseCase ;",
        "    rdfs:range xsd:string .",
        "",
        "app:ToolUseContract a owl:Class ;",
        '    rdfs:label "Blender Tool-Use Contract" ;',
        '    rdfs:comment "The ordered tool calls of one use case: which tools, in which order, with which arguments." ;',
        "    rdfs:subClassOf :Task, core:Task .",
        "",
        "app:DataLocation a owl:Class ;",
        '    rdfs:label "Blender Data Location" ;',
        '    rdfs:comment "Where one kind of Blender data lives and how it is reached." ;',
        "    rdfs:subClassOf :Artifact, core:Artifact .",
        "",
        "app:usesSkill a owl:DatatypeProperty ;",
        '    rdfs:comment "The skill that carries the numbered steps of the use case." ;',
        "    rdfs:domain app:BlenderUseCase ;",
        "    rdfs:range xsd:string .",
        "",
        "app:hasPrompt a owl:DatatypeProperty ;",
        '    rdfs:comment "The prompt (agent definition) that performs the use case." ;',
        "    rdfs:domain app:BlenderUseCase ;",
        "    rdfs:range xsd:string .",
        "",
        "app:toolOrder a owl:DatatypeProperty ;",
        '    rdfs:comment "One ordered tool call of a contract, as index:tool." ;',
        "    rdfs:domain app:ToolUseContract ;",
        "    rdfs:range xsd:string .",
        "",
        "app:contractFor a owl:ObjectProperty ;",
        '    rdfs:comment "Links a tool-use contract to its use case." ;',
        "    rdfs:domain app:ToolUseContract ;",
        "    rdfs:range app:BlenderUseCase .",
        "",
        "app:locatedAt a owl:DatatypeProperty ;",
        '    rdfs:comment "How the data is reached." ;',
        "    rdfs:domain app:DataLocation ;",
        "    rdfs:range xsd:string .",
        "",
        "app:app a app:BlenderApp ;",
        f'    app:appNamespace "{app}" ;',
        f'    app:appVersion "{snapshot.version}" .',
        "",
    ]
    for cls in source.classes:
        if cls.parent not in ALLOWED_PARENTS:
            raise ContentError(
                CONTENT_PARENT_UNKNOWN,
                f"{app}: class {cls.name!r} names parent {cls.parent!r}",
            )
        lines.append(f"app:{cls.name} a owl:Class ;")
        lines.append(f'    rdfs:label "{cls.name}" ;')
        if cls.description:
            lines.append(f'    rdfs:comment "{cls.description}" ;')
        lines.append(f"    rdfs:subClassOf :{cls.parent}, core:{cls.parent} .")
        lines.append("")
    for func in source.functionalities:
        _check_tools(app, func.tools, snapshot)
        lines.append(f"app:use_case_{_slug(func.name)} a app:BlenderUseCase ;")
        lines.append("    app:forApp app:app ;")
        for tool in func.tools:
            lines.append(f'    app:usesToolName "{_tool_ref(app, tool)}" ;')
        lines.append(f'    app:usesSkill "{skill_name(app, func.name)}" ;')
        lines.append(f'    app:hasPrompt "{app}-{func.name}" ;')
        lines[-1] = lines[-1].rstrip(" ;") + " ."
        lines.append("")
        lines.append(f"app:contract_{_slug(func.name)} a app:ToolUseContract ;")
        lines.append(f"    app:contractFor app:use_case_{_slug(func.name)} ;")
        for index, step in enumerate(func.steps, 1):
            if step.tool:
                lines.append(
                    f'    app:toolOrder "{index}:{_tool_ref(app, step.tool)}" ;'
                )
        lines[-1] = lines[-1].rstrip(" ;") + " ."
        lines.append("")
    for loc in source.data_locations:
        lines.append(f"app:data_{_slug(loc.name)} a app:DataLocation ;")
        lines.append(f'    rdfs:label "{loc.name}" ;')
        lines.append(f'    app:locatedAt "{_esc(loc.where)}" .')
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _esc(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def _slug(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]+", "_", name).strip("_")
